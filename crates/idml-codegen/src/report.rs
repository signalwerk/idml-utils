//! HTML reports of the schema changes from one IDML version to the next,
//! generated from the schema history: an overview and one page per step,
//! sharing `style.css` (from `report.css`), with `.nojekyll` for GitHub Pages.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::emit::enum_variants;
use crate::history::{Event, History};
use crate::lower::each_field;
use crate::model::*;
use crate::upgrade::{Action, Upgrades};

/// The report files by name.
pub fn html(history: &History, model: &Model, upgrades: &Upgrades) -> BTreeMap<String, String> {
    let rust = rust_items(model);
    let steps = steps(history);
    let mut files = BTreeMap::new();
    files.insert(".nojekyll".to_owned(), String::new());
    files.insert(
        "style.css".to_owned(),
        format!("/* @generated by idml-codegen from crates/idml-codegen/src/report.css. Do not edit. */\n{}", include_str!("report.css")),
    );
    files.insert("index.html".to_owned(), index(history, &steps, upgrades));
    files.insert("upgrades.html".to_owned(), upgrades_page(history, upgrades, &rust));
    for (n, step) in steps.iter().enumerate() {
        let previous = n.checked_sub(1).and_then(|p| steps.get(p));
        files.insert(file_name(history, step), step_page(history, step, previous, steps.get(n + 1), &rust, upgrades));
    }
    files
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Change {
    Added,
    Moved,
    Removed,
    Changed,
    Restored,
}

impl Change {
    const ALL: [Change; 5] = [Change::Added, Change::Moved, Change::Removed, Change::Changed, Change::Restored];

    fn name(self) -> &'static str {
        match self {
            Change::Added => "added",
            Change::Moved => "moved",
            Change::Removed => "removed",
            Change::Changed => "changed",
            Change::Restored => "restored",
        }
    }
}

struct Row {
    id: String,
    change: Change,
    before: Option<String>,
    /// For a moved item, where it is now.
    after: Option<String>,
}

/// The changes between snapshot `to - 1` and snapshot `to`.
struct Step {
    to: usize,
    rows: Vec<Row>,
    /// Items first covered here although an earlier snapshot exists.
    uncompared: usize,
}

impl Step {
    fn count(&self, change: Change) -> usize {
        self.rows.iter().filter(|r| r.change == change).count()
    }
}

fn steps(h: &History) -> Vec<Step> {
    let mut steps: Vec<Step> = (1..h.versions.len()).map(|to| Step { to, rows: Vec::new(), uncompared: 0 }).collect();
    for (id, states) in &h.items {
        let state = |i: usize| states.get(i).cloned().flatten();
        match h.since(id) {
            Some((first, Some(_))) if first > 0 => {
                if let Some(step) = steps.get_mut(first - 1) {
                    step.rows.push(Row { id: id.clone(), change: Change::Added, before: None, after: state(first) });
                }
            }
            Some((first, None)) if first > 0 => {
                if let Some(step) = steps.get_mut(first - 1) {
                    step.uncompared += 1;
                }
            }
            _ => {}
        }
        for (i, previous, event) in h.events(id) {
            let before = previous.and_then(state);
            let row = match event {
                Event::Changed => Row { id: id.clone(), change: Change::Changed, before, after: state(i) },
                Event::Removed => match h.moved(id, i) {
                    Some(now) => Row { id: id.clone(), change: Change::Moved, before, after: Some(now) },
                    None => Row { id: id.clone(), change: Change::Removed, before, after: None },
                },
                Event::Restored => Row { id: id.clone(), change: Change::Restored, before: None, after: state(i) },
            };
            if let Some(step) = i.checked_sub(1).and_then(|s| steps.get_mut(s)) {
                step.rows.push(row);
            }
        }
    }
    for step in &mut steps {
        step.rows.sort_by(|a, b| (anchor(&a.id), a.change, &a.id).cmp(&(anchor(&b.id), b.change, &b.id)));
    }
    steps
}

/// The definition an item belongs to.
fn anchor(id: &str) -> &str {
    id.split(['/', '=', '|']).next().unwrap_or(id)
}

const KINDS: [&str; 6] = ["definition", "attribute", "element", "enumeration value", "choice branch", "text content"];

fn kind(id: &str) -> &'static str {
    let rel = &id[anchor(id).len()..];
    let last = rel.rsplit('/').next().unwrap_or(rel);
    if rel.is_empty() {
        KINDS[0]
    } else if rel.starts_with('=') {
        KINDS[3]
    } else if last.contains('|') {
        KINDS[4]
    } else if last.starts_with('@') {
        KINDS[1]
    } else if last == "text()" {
        KINDS[5]
    } else {
        KINDS[2]
    }
}

/// A fingerprint in words.
fn readable(fp: &str) -> String {
    match fp {
        "1" => "required".to_owned(),
        "?" => "optional".to_owned(),
        "*" => "zero or more".to_owned(),
        "+" => "one or more".to_owned(),
        other => other.to_owned(),
    }
}

/// The Rust items of the current model, by schema item.
fn rust_items(model: &Model) -> BTreeMap<String, Vec<String>> {
    let mut out: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut add = |trace: &Trace, rust: String| {
        for id in &trace.items {
            out.entry(id.clone()).or_default().push(rust.clone());
        }
    };
    for t in &model.types {
        add(&t.trace, t.name.clone());
        match &t.kind {
            TypeKind::Struct(c) => {
                for a in &c.attrs {
                    add(&a.trace, format!("{}.{}", t.name, a.field));
                }
                if let Body::Text { field, trace, .. } = &c.body {
                    add(trace, format!("{}.{field}", t.name));
                }
                each_field(c, &mut |f| add(&f.trace, format!("{}.{}", t.name, f.field)));
            }
            TypeKind::Choice(vs) => vs.iter().for_each(|v| add(&v.trace, format!("{}::{}", t.name, v.name))),
            TypeKind::Enum(ls) => {
                for (l, v) in ls.iter().zip(enum_variants(ls)) {
                    add(&l.trace, format!("{}::{v}", t.name));
                }
            }
            TypeKind::Children(ms) => ms.iter().for_each(|m| add(&m.trace, format!("{}::{}", t.name, m.name))),
            TypeKind::Union(_) | TypeKind::Ranged { .. } | TypeKind::Alias(_) => {}
        }
    }
    for v in out.values_mut() {
        v.sort();
        v.dedup();
    }
    out
}

fn file_name(h: &History, step: &Step) -> String {
    let clean = |s: String| s.chars().map(|c| if c.is_ascii_alphanumeric() || c == '.' { c } else { '_' }).collect::<String>();
    format!("{}-to-{}.html", clean(h.label(step.to - 1)), clean(h.label(step.to)))
}

fn title(h: &History, step: &Step) -> String {
    format!("{} → {}", h.label(step.to - 1), h.label(step.to))
}

fn product(h: &History, i: usize) -> String {
    let v = &h.versions[i];
    let name = v.product.as_deref().map(|p| format!("InDesign {p}")).unwrap_or_else(|| "InDesign".to_owned());
    match &v.build {
        Some(b) => format!("{name} ({b})"),
        None => name,
    }
}

fn gap_note(h: &History, step: &Step) -> Option<String> {
    let (a, b) = (step.to - 1, step.to);
    h.gap(a, b).then(|| {
        format!(
            "There are no schemas between {0} and {1}, so these changes happened after {0}, by {1} (written <code>&gt; {0} &lt;= {1}</code>).",
            esc(&h.label(a)),
            esc(&h.label(b))
        )
    })
}

// -- pages -------------------------------------------------------------------------

fn index(h: &History, steps: &[Step], upgrades: &Upgrades) -> String {
    let mut b = String::new();
    b.push_str("<h1>IDML schema changes</h1>\n");
    b.push_str(
        "<p class=\"lead\">How the IDML schemas changed from one InDesign version to the next. Generated by \
         <code>idml-codegen</code> from the schemas in <code>schemas/</code>; each step compares two snapshots \
         item by item: definitions, attributes, child elements, enumeration values, choice branches and text content.</p>\n",
    );
    b.push_str("<h2>Steps</h2>\n<div class=\"scroll\"><table>\n<tr><th>Step</th>");
    for c in Change::ALL {
        let _ = write!(b, "<th class=\"num\">{}</th>", cap(c.name()));
    }
    b.push_str("<th>Note</th></tr>\n");
    for step in steps {
        let _ = write!(b, "<tr><td><a href=\"{}\">{}</a></td>", file_name(h, step), esc(&title(h, step)));
        for c in Change::ALL {
            let n = step.count(c);
            let class = if n > 0 { c.name() } else { "zero" };
            let _ = write!(b, "<td class=\"num {class}\">{n}</td>");
        }
        let note =
            if h.gap(step.to - 1, step.to) { format!("no schemas between {} and {}", h.label(step.to - 1), h.label(step.to)) } else { String::new() };
        let _ = writeln!(b, "<td class=\"muted\">{}</td></tr>", esc(&note));
    }
    b.push_str("</table></div>\n<h2>Versions</h2>\n<div class=\"scroll\"><table>\n");
    b.push_str("<tr><th>DOMVersion</th><th>InDesign</th><th>Form</th><th class=\"num\">Items</th><th>Schemas</th></tr>\n");
    for (i, v) in h.versions.iter().enumerate() {
        let items = h.items.iter().filter(|(id, s)| h.covers(i, id) && s.get(i).is_some_and(Option::is_some)).count();
        let form = if v.single { "single file" } else { "package" };
        let same = if v.same_as.is_empty() { String::new() } else { format!(" (same items as {})", v.same_as.join(", ")) };
        let _ = writeln!(
            b,
            "<tr><td>{}</td><td>{}{}</td><td>{form}</td><td class=\"num\">{items}</td><td><code>schemas/{}</code></td></tr>",
            esc(&h.label(i)),
            esc(&product(h, i)),
            esc(&same),
            esc(&v.dir)
        );
    }
    b.push_str("</table></div>\n");
    let count = |f: fn(&Action) -> bool| upgrades.rules.iter().filter(|r| f(&r.action)).count();
    let _ = writeln!(
        b,
        "<h2>Reading older documents</h2>\n<p>Documents of older versions are read into the current model after \
         <a href=\"upgrades.html\">{} rules</a> from <code>crates/idml/schema-upgrades.tsv</code>: {} drop data (with a warning), \
         {} put elements where they are allowed now, {} map or complete values and {} confirm that old values stay valid.</p>",
        upgrades.rules.len(),
        count(|a| matches!(a, Action::Drop)),
        count(|a| matches!(a, Action::Wrap(_))),
        count(|a| matches!(a, Action::Value(_) | Action::Default(_))),
        count(|a| matches!(a, Action::Keep)),
    );
    b.push_str(
        "<h2>Reading the reports</h2>\n<ul>\n\
         <li><b>Added</b> items are in the version, not in the one before; <b>removed</b> items the other way round; \
         <b>moved</b> items are no longer allowed where they were but still in the same parent, nested in elements without an identity \
         (a <code>&lt;TextFrame&gt;</code> in <code>&lt;Story&gt;</code> is now in <code>&lt;CharacterStyleRange&gt;</code>; an attribute became a \
         <code>&lt;Properties&gt;</code> element); <b>changed</b> items have a different type, presence or occurrence; \
         <b>restored</b> items were removed earlier and are back.</li>\n\
         <li>Where versions are missing between two snapshots, a change happened somewhere in between.</li>\n\
         <li>6.0 exists only as a single-file schema, which has no designmap and no part roots: those items are first compared from 7.0 on. \
         For everything else it lists exactly what the package schemas do (checked with InDesign 21.5.1.73, generated in both forms).</li>\n\
         <li>The <i>Rust</i> column names the item of the generated model that represents a schema item today.</li>\n\
         <li>A renamed item shows as removed and added. Move hints come from the schemas alone; whether InDesign means the same \
         by the new place is a judgement, recorded in <code>crates/idml/schema-upgrades.tsv</code>.</li>\n</ul>\n",
    );
    page("IDML schema changes", &b)
}

fn step_page(
    h: &History,
    step: &Step,
    previous: Option<&Step>,
    next: Option<&Step>,
    rust: &BTreeMap<String, Vec<String>>,
    upgrades: &Upgrades,
) -> String {
    let mut b = String::new();
    b.push_str("<nav><a href=\"index.html\">All versions</a><a href=\"upgrades.html\">Reading older documents</a>");
    if let Some(p) = previous {
        let _ = write!(b, "<a href=\"{}\">← {}</a>", file_name(h, p), esc(&title(h, p)));
    }
    if let Some(n) = next {
        let _ = write!(b, "<a href=\"{}\">{} →</a>", file_name(h, n), esc(&title(h, n)));
    }
    b.push_str("</nav>\n");
    let _ = writeln!(b, "<h1>IDML {}</h1>", esc(&title(h, step)));
    let _ = writeln!(b, "<p class=\"lead\">{} → {}</p>", esc(&product(h, step.to - 1)), esc(&product(h, step.to)));
    if let Some(note) = gap_note(h, step) {
        let _ = writeln!(b, "<p class=\"note\">{note}</p>");
    }
    if step.uncompared > 0 {
        let _ = writeln!(
            b,
            "<p class=\"note\">{} items of the designmap and the part roots appear here for the first time without being new: \
             {} is a single-file schema that has neither, so they are not compared.</p>",
            step.uncompared,
            esc(&h.label(step.to - 1))
        );
    }

    // Counts by kind of item.
    b.push_str("<h2>Summary</h2>\n<div class=\"scroll\"><table>\n<tr><th>Kind</th>");
    for c in Change::ALL {
        let _ = write!(b, "<th class=\"num\">{}</th>", cap(c.name()));
    }
    b.push_str("</tr>\n");
    for k in KINDS {
        let _ = write!(b, "<tr><td>{}</td>", cap(k));
        for c in Change::ALL {
            let n = step.rows.iter().filter(|r| r.change == c && kind(&r.id) == k).count();
            let class = if n > 0 { c.name() } else { "zero" };
            let _ = write!(b, "<td class=\"num {class}\">{n}</td>");
        }
        b.push_str("</tr>\n");
    }
    b.push_str("</table></div>\n");

    // By definition.
    let mut groups: BTreeMap<&str, Vec<&Row>> = BTreeMap::new();
    for r in &step.rows {
        groups.entry(anchor(&r.id)).or_default().push(r);
    }
    if groups.is_empty() {
        b.push_str("<p>No changes.</p>\n");
        return page(&format!("IDML {}", title(h, step)), &b);
    }
    let _ = writeln!(
        b,
        "<h2>Definitions ({})</h2>\n<p class=\"muted\">New definitions in green, removed ones struck through.</p>\n<p class=\"toc\">",
        groups.len()
    );
    for (def, rows) in &groups {
        let whole = rows.iter().find(|r| r.id == *def).map(|r| r.change);
        let class = whole.map_or("", |c| c.name());
        let _ = write!(b, "<a class=\"{class}\" href=\"#{}\">{}</a> ", esc(def), esc(def));
    }
    b.push_str("</p>\n");
    for (def, rows) in &groups {
        let whole = rows.iter().find(|r| r.id == *def).map(|r| r.change);
        let types = rust.get(*def).map(|v| v.join(", ")).unwrap_or_default();
        let _ = write!(b, "<section id=\"{}\">\n<h3><code>{}</code>", esc(def), esc(def));
        if let Some(c) = whole {
            let _ = write!(b, " <span class=\"badge {0}\">{0}</span>", c.name());
        }
        if let Some(rule) = upgrades.rule(def).filter(|r| r.item == *def && whole.is_some_and(|c| c != Change::Added)) {
            let _ = write!(b, " <span class=\"rust\">older documents: {}</span>", esc(&rule.action.describe()));
        }
        if !types.is_empty() {
            let _ = write!(b, " <span class=\"rust\">{}</span>", esc(&types));
        }
        b.push_str("</h3>\n");
        let members: Vec<&&Row> = rows.iter().filter(|r| r.id != *def).collect();
        if members.is_empty() {
            b.push_str("</section>\n");
            continue;
        }
        // A new or removed definition: its items are listed folded.
        let folded = matches!(whole, Some(Change::Added | Change::Removed));
        if folded {
            let _ = writeln!(b, "<details><summary>{} items</summary>", members.len());
        }
        b.push_str(
            "<div class=\"scroll\"><table class=\"items\">\n\
             <colgroup><col class=\"c-change\"><col class=\"c-item\"><col class=\"c-schema\"><col class=\"c-rust\"></colgroup>\n\
             <tr><th></th><th>Item</th><th>Schema</th><th>Rust</th></tr>\n",
        );
        for r in members {
            let rel = r.id[def.len()..].trim_start_matches(['/', '=']);
            let state = |tag: &str, s: &Option<String>| match s.as_deref().map(readable) {
                Some(s) if !s.is_empty() => format!("<{tag}>{}</{tag}>", esc(&s)),
                _ => String::new(),
            };
            let schema = match r.change {
                Change::Changed => state("del", &r.before) + &state("ins", &r.after),
                Change::Moved => format!(
                    "{}<span class=\"now\">now <code>{}</code></span>",
                    state("del", &r.before),
                    breakable(r.after.as_deref().unwrap_or_default())
                ),
                Change::Removed => state("del", &r.before),
                Change::Added | Change::Restored => state("span", &r.after),
            } + &upgrade_note(upgrades, r);
            let rust = rust.get(&r.id).map(|v| v.join(", ")).unwrap_or_default();
            let _ = writeln!(
                b,
                "<tr><td><span class=\"badge {0}\">{0}</span></td><td><code>{1}</code></td><td>{schema}</td><td><code>{2}</code></td></tr>",
                r.change.name(),
                breakable(rel),
                breakable(&rust)
            );
        }
        b.push_str("</table></div>\n");
        if folded {
            b.push_str("</details>\n");
        }
        b.push_str("</section>\n");
    }
    page(&format!("IDML {}", title(h, step)), &b)
}

/// How documents of older versions are read where a removed, moved or
/// changed item has its own rule, or goes with a dropped definition or
/// element (but not for each item inside one).
fn upgrade_note(upgrades: &Upgrades, r: &Row) -> String {
    if matches!(r.change, Change::Added | Change::Restored) {
        return String::new();
    }
    let Some(rule) = upgrades.rule(&r.id) else { return String::new() };
    let what = if rule.item == r.id {
        rule.action.describe()
    } else if r.id.starts_with(&rule.item) {
        return String::new();
    } else {
        format!("{} with <code>{}</code>", rule.action.describe(), esc(&rule.item))
    };
    let note = if rule.note.is_empty() { String::new() } else { format!(": {}", esc(&rule.note)) };
    format!("<span class=\"upgrade\">Older documents: {}{note}</span>", if rule.item == r.id { esc(&what) } else { what })
}

/// Every rule of `schema-upgrades.tsv`, with the versions it applies to.
fn upgrades_page(h: &History, upgrades: &Upgrades, rust: &BTreeMap<String, Vec<String>>) -> String {
    let mut b = String::new();
    b.push_str("<nav><a href=\"index.html\">All versions</a></nav>\n<h1>Reading older documents</h1>\n");
    let _ = writeln!(
        b,
        "<p class=\"lead\">The <code>idml</code> crate reads documents of older <code>DOMVersion</code>s into the {} model. \
         Before a part is read, it is edited by these rules: one for every schema item that an older version has and {} has not, \
         or has differently. They come from <code>crates/idml/schema-upgrades.tsv</code>; <code>idml-codegen</code> checks them \
         against the schemas and fails if one is missing or not needed. Dropping data is reported as a warning. Tests read \
         documents generated from each older schema with the current model.</p>",
        esc(&h.label(h.versions.len() - 1)),
        esc(&h.label(h.versions.len() - 1)),
    );
    // Grouped by the versions they apply to, oldest first.
    let mut groups: BTreeMap<(Option<usize>, String), Vec<usize>> = BTreeMap::new();
    for (i, versions) in upgrades.versions.iter().enumerate() {
        let labels: Vec<String> = versions.iter().map(|v| h.label(*v)).collect();
        groups.entry((versions.first().copied(), labels.join(", "))).or_default().push(i);
    }
    for ((_, labels), rules) in groups {
        let _ = writeln!(b, "<h2>Documents of {}</h2>", esc(&labels));
        b.push_str(
            "<div class=\"scroll\"><table class=\"items\">\n\
             <colgroup><col class=\"c-item\"><col class=\"c-rule\"><col></colgroup>\n\
             <tr><th>Item</th><th>Rule</th><th>Why</th></tr>\n",
        );
        for i in rules {
            let rule = &upgrades.rules[i];
            let kind = match rule.action {
                Action::Drop => "removed",
                Action::Wrap(_) => "moved",
                Action::Value(_) | Action::Default(_) | Action::Keep => "changed",
            };
            let now = rust.get(&rule.item).map(|r| format!(" <span class=\"rust\">{}</span>", breakable(&r.join(", ")))).unwrap_or_default();
            let _ = writeln!(
                b,
                "<tr><td><code>{}</code>{now}</td><td><span class=\"badge {kind}\">{}</span></td><td>{}</td></tr>",
                breakable(&rule.item),
                esc(&rule.action.describe()),
                esc(&rule.note)
            );
        }
        b.push_str("</table></div>\n");
    }
    page("Reading older IDML documents", &b)
}

fn cap(s: &str) -> String {
    let mut c = s.chars();
    c.next().map(|f| f.to_uppercase().collect::<String>() + c.as_str()).unwrap_or_default()
}

/// Escaped, with line breaks allowed after `/` and `.`.
fn breakable(s: &str) -> String {
    esc(s).replace('/', "/<wbr>").replace('.', ".<wbr>")
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

fn page(title: &str, body: &str) -> String {
    format!(
        "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>{}</title>\n<link rel=\"stylesheet\" href=\"style.css\">\n</head>\n<body>\n\
         <!-- @generated by idml-codegen from the schemas in schemas/. Do not edit. -->\n{body}</body>\n</html>\n",
        esc(title)
    )
}
