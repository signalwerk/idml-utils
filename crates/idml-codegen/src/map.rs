//! The schema map: a TSV file with a row for every schema item and the Rust
//! item that represents it. Diffing it between schema versions shows what
//! was added, removed or changed, and how it is represented.

use std::fmt::Write as _;

use crate::emit::type_name;
use crate::model::*;
use crate::schema::Schema;

pub fn tsv(model: &Model, schema: &Schema) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# IDML schema map: each schema item and the Rust item that represents it.");
    let _ = writeln!(out, "# @generated by idml-codegen. Do not edit.");
    let _ = writeln!(out, "# InDesign {}, DOMVersion {}, schema SHA-256 {}", model.indesign_version, model.dom_version, model.sha256);
    for (file, sha) in &model.files {
        let _ = writeln!(out, "# {sha}  {file}");
    }
    for (file, lines) in &model.stray_lines {
        let lines: Vec<String> = lines.iter().map(usize::to_string).collect();
        let _ = writeln!(out, "# {file}: comment lines without '#' read as documentation: {}", lines.join(", "));
    }
    let counts = Counts::of(model);
    let _ = writeln!(
        out,
        "# {} reachable definitions, {} unreachable; {} types: {} structs, {} choices, {} enums ({} literals), \
         {} ranged, {} unions, {} aliases, {} interleaved-children enums; {} attributes, {} literal attributes, {} child elements",
        schema.reachable.len(),
        model.unreachable.len(),
        model.types.len(),
        counts.structs,
        counts.choices,
        counts.enums,
        counts.literals,
        counts.ranged,
        counts.unions,
        counts.aliases,
        counts.children,
        counts.attrs,
        counts.fixed,
        counts.elems,
    );
    let _ = writeln!(out, "# since: the IDML version that introduced the item (see schema-history.tsv); - for items that are not schema items");
    let _ = writeln!(out, "rust\tschema\trust type\tsince");

    let mut ids: Vec<TypeId> = (0..model.types.len()).collect();
    ids.sort_by(|a, b| model.types[*a].name.cmp(&model.types[*b].name));
    for id in ids {
        let t = &model.types[id];
        let root = model.roots.iter().find(|r| r.ty == id).map(|r| format!(", root of {}", r.file)).unwrap_or_default();
        let origin = &t.origin;
        let element = t.element.as_ref().map(|e| format!(" <{e}>")).unwrap_or_default();
        match &t.kind {
            TypeKind::Struct(c) => {
                row(&mut out, &t.name, &format!("{origin}{element}{root}"), "struct", &t.trace);
                content_rows(&mut out, model, &t.name, c);
            }
            TypeKind::Choice(vs) => {
                row(&mut out, &t.name, &format!("{origin}{element}"), "enum (choice)", &t.trace);
                for v in vs {
                    let fixed: Vec<String> = v.fixed.iter().map(|f| format!("@{}={:?}", f.name, f.value)).collect();
                    let payload = match &v.ty {
                        Ty::Unit => "-".to_owned(),
                        ty => describe_ty(model, ty),
                    };
                    let schema = if fixed.is_empty() { v.schema.clone() } else { format!("{} ({})", v.schema, fixed.join(" ")) };
                    row(&mut out, &format!("{}::{}", t.name, v.name), &schema, &payload, &v.trace);
                }
            }
            TypeKind::Enum(literals) => {
                row(&mut out, &t.name, origin, "enum", &t.trace);
                for (lit, variant) in literals.iter().zip(crate::emit::enum_variants(literals)) {
                    row(&mut out, &format!("{}::{variant}", t.name), &format!("{:?}", lit.value), "-", &lit.trace);
                }
            }
            TypeKind::Union(members) => {
                row(&mut out, &t.name, origin, "enum (value choice)", &t.trace);
                for m in members {
                    let name = &model.types[*m].name;
                    row(&mut out, &format!("{}::{name}", t.name), &model.types[*m].origin, name, &model.types[*m].trace);
                }
            }
            TypeKind::Ranged { base, min, max } => {
                let base = match base {
                    Scalar::Int => "i32",
                    Scalar::Short => "i16",
                    Scalar::Double => "f64",
                };
                row(&mut out, &t.name, origin, &format!("{base} in {min}..={max}"), &t.trace);
            }
            TypeKind::Alias(v) => row(&mut out, &t.name, origin, &format!("type = {}", value_rust(model, v)), &t.trace),
            TypeKind::Children(ms) => {
                row(&mut out, &t.name, origin, "enum (interleaved children, in document order)", &t.trace);
                for m in ms {
                    row(&mut out, &format!("{}::{}", t.name, m.name), &describe_elem(&m.elem), &describe_ty(model, &m.elem.ty), &m.trace);
                }
            }
        }
    }
    for (name, files) in &model.unreachable {
        row(&mut out, "-", &format!("{name} (in {})", files.join(", ")), "unreachable from every part: not generated", &Trace::default());
    }
    out
}

fn row(out: &mut String, rust: &str, schema: &str, ty: &str, trace: &Trace) {
    let clean = |s: &str| s.replace(['\t', '\n'], " ");
    let since = trace.since.as_deref().map(|s| s.trim_start_matches("Since IDML ").trim_end_matches('.')).unwrap_or("-");
    let _ = writeln!(out, "{}\t{}\t{}\t{}", clean(rust), clean(schema), clean(ty), clean(since));
}

fn content_rows(out: &mut String, model: &Model, owner: &str, c: &Content) {
    for f in &c.fixed {
        row(out, owner, &format!("@{}={:?}", f.name, f.value), "literal: checked on read, written always", &Trace::default());
    }
    for a in &c.attrs {
        let ty = value_rust(model, &a.ty);
        let ty = if a.required { ty } else { format!("Option<{ty}>") };
        row(out, &format!("{owner}.{}", a.field), &format!("@{}: {}", a.name, a.schema), &ty, &a.trace);
    }
    match &c.body {
        Body::Empty => {}
        Body::Text { field, ty, schema, trace } => row(out, &format!("{owner}.{field}"), &format!("text: {schema}"), &value_rust(model, ty), trace),
        Body::Children(items) => {
            for item in items {
                let (slots, interleaved) = match item {
                    Item::Elem(f) => (vec![Slot::Elem(f.clone())], ""),
                    Item::Interleave(slots) => (slots.clone(), " (interleaved)"),
                };
                for s in slots {
                    match s {
                        Slot::Elem(f) => {
                            let occurs = match f.occurs {
                                Occurs::One => "",
                                Occurs::Optional => "?",
                                Occurs::Many => "*",
                            };
                            let mut ty = describe_ty(model, &f.elem.ty);
                            if f.elem.part == Some(PartRef::Path) {
                                ty = format!("Part<{ty}>");
                            }
                            if f.boxed {
                                ty = format!("Box<{ty}>");
                            }
                            let ty = match f.occurs {
                                Occurs::One => ty,
                                Occurs::Optional => format!("Option<{ty}>"),
                                Occurs::Many => format!("Vec<{ty}>"),
                            };
                            let schema = format!("{}{occurs}{interleaved}", describe_elem(&f.elem));
                            row(out, &format!("{owner}.{}", f.field), &schema, &ty, &f.trace);
                        }
                        Slot::Group { field, ty } => {
                            let names = match &model.types[ty].kind {
                                TypeKind::Children(ms) => ms.iter().map(|m| format!("<{}>*", m.elem.name)).collect::<Vec<_>>().join(" & "),
                                _ => String::new(),
                            };
                            row(out, &format!("{owner}.{field}"), &names, &format!("Vec<{}>", type_name(model, ty)), &Trace::default());
                        }
                    }
                }
            }
        }
    }
}

/// An element with its collapsed content, e.g. `<Label>{<KeyValuePair>*}`.
fn describe_elem(e: &Elem) -> String {
    let mut s = format!("<{}", e.name);
    for f in &e.fixed {
        let _ = write!(s, " {}={:?}", f.name, f.value);
    }
    match &e.part {
        Some(PartRef::Fixed(src)) => {
            let _ = write!(s, " src={src:?}");
        }
        Some(PartRef::Path) => s.push_str(" src=path"),
        None => {}
    }
    s.push('>');
    match &e.ty {
        Ty::Unit => s.push_str("{empty}"),
        Ty::Value(_) => s.push_str("{text}"),
        Ty::Named(_) => {}
        Ty::Vec(inner) => {
            let _ = write!(s, "{{{}*}}", describe_elem(inner));
        }
        Ty::Array(inner, n) => {
            let _ = write!(s, "{{{}{{{n}}}}}", describe_elem(inner));
        }
        Ty::Wrap(inner) => {
            let _ = write!(s, "{{{}}}", describe_elem(inner));
        }
    }
    s
}

fn describe_ty(model: &Model, ty: &Ty) -> String {
    match ty {
        Ty::Unit => "()".to_owned(),
        Ty::Value(v) => value_rust(model, v),
        Ty::Named(id) => type_name(model, *id).to_owned(),
        Ty::Vec(e) => format!("Vec<{}>", elem_ty(model, e)),
        Ty::Array(e, n) => format!("[{}; {n}]", elem_ty(model, e)),
        Ty::Wrap(e) => elem_ty(model, e),
    }
}

fn elem_ty(model: &Model, e: &Elem) -> String {
    match e.part {
        Some(PartRef::Path) => format!("Part<{}>", describe_ty(model, &e.ty)),
        _ => describe_ty(model, &e.ty),
    }
}

fn value_rust(model: &Model, v: &ValueType) -> String {
    match v {
        ValueType::String => "String".to_owned(),
        ValueType::Bool => "bool".to_owned(),
        ValueType::Int => "i32".to_owned(),
        ValueType::Short => "i16".to_owned(),
        ValueType::Double => "f64".to_owned(),
        ValueType::DateTime => "DateTime".to_owned(),
        ValueType::Token => "Token".to_owned(),
        ValueType::PartPath => "PartPath".to_owned(),
        ValueType::Named(id) => type_name(model, *id).to_owned(),
        ValueType::Array(v, n) => format!("[{}; {n}]", value_rust(model, v)),
        ValueType::List(v) => format!("Vec<{}>", value_rust(model, v)),
    }
}

#[derive(Default)]
struct Counts {
    structs: usize,
    choices: usize,
    enums: usize,
    literals: usize,
    ranged: usize,
    unions: usize,
    aliases: usize,
    children: usize,
    attrs: usize,
    fixed: usize,
    elems: usize,
}

impl Counts {
    fn of(model: &Model) -> Counts {
        let mut c = Counts::default();
        for t in &model.types {
            match &t.kind {
                TypeKind::Struct(content) => {
                    c.structs += 1;
                    c.attrs += content.attrs.len();
                    c.fixed += content.fixed.len();
                    crate::lower::each_field(content, &mut |_| c.elems += 1);
                }
                TypeKind::Choice(_) => c.choices += 1,
                TypeKind::Enum(l) => {
                    c.enums += 1;
                    c.literals += l.len();
                }
                TypeKind::Ranged { .. } => c.ranged += 1,
                TypeKind::Union(_) => c.unions += 1,
                TypeKind::Alias(_) => c.aliases += 1,
                TypeKind::Children(_) => c.children += 1,
            }
        }
        c
    }
}
